import 'dotenv/config';
import assert from 'node:assert/strict';
import { createHash, randomUUID } from 'node:crypto';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
import pool from '../src/db.js';
import { createPasswordReset, createUser } from '../src/authService.js';

process.env.EMAIL_TRANSPORT = 'simulated';
const base = process.env.QA_EMAIL_APP_URL ?? 'http://127.0.0.1:5173/';
const origin = new URL(base).origin;
const suffix = randomUUID();
const adminEmail = `qa-email-admin-${suffix}@invalid.example`;
const pendingEmail = `qa-email-pending-${suffix}@invalid.example`;
const invitedEmail = `qa-email-invited-${suffix}@invalid.example`;
const expiredEmail = `qa-email-expired-${suffix}@invalid.example`;
const password = 'Local-QA-Password-2026!';
const changedPassword = 'Local-QA-Password-Changed-2026!';
let companyId = 0;
let userIds: number[] = [];
const browser = await chromium.launch({ headless: true });
mkdirSync('artifacts/qa-email', { recursive: true });
try {
  const [company] = await pool.execute<any>('INSERT INTO companies (nombre_comercial) VALUES (?)', [`TEMP EMAIL QA ${suffix}`]);
  companyId = Number(company.insertId);
  const adminId = await createUser(adminEmail, password, 'user', 'QA', 'Admin');
  userIds.push(adminId);
  await pool.execute("INSERT INTO company_memberships (user_id,company_id,role,status) VALUES (?,?,'admin','active')", [adminId, companyId]);

  const desktop = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await desktop.goto(base);
  await desktop.getByRole('button', { name: 'Crear cuenta' }).click();
  await desktop.getByLabel('Nombre').fill('Correo');
  await desktop.getByLabel('Apellido').fill('Pendiente');
  await desktop.getByLabel('Correo electrónico').fill(pendingEmail);
  await desktop.getByLabel('Contraseña').fill(password);
  await desktop.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
  await desktop.getByRole('heading', { name: 'Revisa tu correo' }).waitFor({timeout:8000}).catch(async()=>{throw new Error(`registration UI did not advance: ${(await desktop.locator('body').innerText()).slice(0,500)}`)});
  const [pendingAccount] = await pool.query<any[]>('SELECT id FROM app_users WHERE email_normalized=?', [pendingEmail]);
  userIds.push(Number(pendingAccount[0].id));
  let session = await desktop.request.get(`${origin}/api/auth/session`);
  assert.equal((await session.json()).emailVerified, false);
  const blocked = await desktop.evaluate(async () => {
    const csrf = document.cookie.split('; ').find((item) => item.startsWith('oportuna.csrf='))?.split('=').slice(1).join('=') ?? '';
    const response = await fetch('/api/onboarding/company', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': decodeURIComponent(csrf) }, body: '{}' });
    return response.status;
  });
  assert.equal(blocked, 403, 'unverified users cannot register or access a company');
  const firstInbox = await desktop.request.get(`${origin}/api/auth/local-outbox?email=${encodeURIComponent(pendingEmail)}&purpose=verification`);
  const firstMail = (await firstInbox.json() as any).messages[0];
  const firstToken = new URL(firstMail.link).searchParams.get('verifyEmail');
  await desktop.getByRole('button', { name: 'Reenviar enlace' }).click();
  await desktop.getByText(/Si tu cuenta necesita verificación/).waitFor();
  const oldTokenResponse = await desktop.request.post(`${origin}/api/auth/email-verification/confirm`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { token: firstToken } });
  assert.equal(oldTokenResponse.status(), 400, 'resending invalidates the previous verification token');
  await desktop.getByRole('button', { name: 'Reenviar enlace' }).click();
  await desktop.getByText(/Si tu cuenta necesita verificación/).waitFor();
  await desktop.getByRole('button', { name: 'Reenviar enlace' }).click();
  await desktop.getByText(/Si tu cuenta necesita verificación/).waitFor();
  await desktop.getByRole('button', { name: 'Reenviar enlace' }).click();
  await desktop.getByText(/Demasiadas solicitudes/).waitFor();
  await desktop.getByRole('button', { name: 'Buzón local de prueba' }).click();
  const newInbox = await desktop.request.get(`${origin}/api/auth/local-outbox?email=${encodeURIComponent(pendingEmail)}&purpose=verification`);
  const newMail = (await newInbox.json() as any).messages[0];
  const crossDevice = await browser.newPage({ viewport: { width: 375, height: 667 } });
  await crossDevice.goto(newMail.link);
  await crossDevice.getByRole('button', { name: 'Verificar cuenta' }).click();
  await crossDevice.getByText('Correo verificado. Inicia sesión para continuar.').waitFor();
  await desktop.reload();
  await desktop.getByRole('heading', { name: 'Conecta tu empresa' }).waitFor({ timeout: 8000 });
  await desktop.screenshot({ path: 'artifacts/qa-email/verification-desktop.png', fullPage: true });
  session = await desktop.request.get(`${origin}/api/auth/session`);
  assert.equal((await session.json()).emailVerified, true);
  const verifiedInbox = await desktop.request.get(`${origin}/api/auth/local-outbox?email=${encodeURIComponent(pendingEmail)}&purpose=verification`);
  const verifiedMail = (await verifiedInbox.json() as any).messages[0];
  const reusedToken = new URL(verifiedMail.link).searchParams.get('verifyEmail');
  const reused = await desktop.request.post(`${origin}/api/auth/email-verification/confirm`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { token: reusedToken } });
  assert.equal(reused.status(), 400, 'verification token cannot be reused');
  const duplicateToken = await desktop.evaluate(() => new URLSearchParams(location.search).get('verifyEmail'));
  assert.equal(duplicateToken, null, 'verification token is removed from the address bar');

  const resetPage = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await resetPage.goto(base);
  await resetPage.getByRole('button', { name: 'Olvidé mi contraseña' }).click();
  await resetPage.getByLabel('Correo electrónico').fill(pendingEmail);
  await resetPage.getByRole('button', { name: 'Solicitar recuperación' }).click();
  await resetPage.getByText(/Si existe una cuenta/).waitFor();
  const resetResponse = await resetPage.request.post(`${origin}/api/auth/password-reset/request`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { email: 'unknown-account@example.invalid' } });
  assert.equal(resetResponse.status(), 202);
  assert.deepEqual(await resetResponse.json(), await (await resetPage.request.post(`${origin}/api/auth/password-reset/request`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { email: pendingEmail } })).json());
  await resetPage.getByRole('button', { name: 'Abrir buzón local de prueba' }).click();
  const resetInbox = await resetPage.request.get(`${origin}/api/auth/local-outbox?email=${encodeURIComponent(pendingEmail)}&purpose=password-reset`);
  const resetMail = (await resetInbox.json() as any).messages[0];
  const resetToken = new URL(resetMail.link).searchParams.get('resetPassword');
  await resetPage.getByRole('link', { name: 'Abrir enlace de recuperación simulado' }).click();
  await resetPage.getByLabel('Nueva contraseña').fill(changedPassword);
  await resetPage.getByRole('button', { name: 'Actualizar contraseña' }).click();
  await resetPage.getByText('Contraseña actualizada. Inicia sesión nuevamente.').waitFor();
  const reusedReset = await resetPage.request.post(`${origin}/api/auth/password-reset/complete`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { token: resetToken, password: changedPassword } });
  assert.equal(reusedReset.status(), 400, 'password reset token cannot be reused');
  const pendingReset = await createPasswordReset(pendingEmail);
  assert.ok(pendingReset);
  const expiredResetToken = pendingReset!.token;
  const resetHash = createHash('sha256').update(expiredResetToken).digest();
  await pool.execute('UPDATE password_reset_tokens SET expires_at=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 MINUTE) WHERE token_hash=?', [resetHash]);
  const expiredReset = await resetPage.request.post(`${origin}/api/auth/password-reset/complete`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { token: expiredResetToken, password: changedPassword } });
  assert.equal(expiredReset.status(), 400, 'expired password reset token is rejected');
  await resetPage.screenshot({ path: `artifacts/qa-email/password-reset-mobile.png`, fullPage: true });

  const adminPage = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await adminPage.goto(base);
  await adminPage.getByLabel('Correo electrónico').fill(adminEmail);
  await adminPage.getByLabel('Contraseña').fill(password);
  await adminPage.getByRole('button', { name: 'Entrar' }).click();
  await adminPage.getByText('Resumen', { exact: true }).first().waitFor({ timeout: 8000 });
  const cookies = await adminPage.context().cookies();
  const csrf = cookies.find((cookie) => cookie.name === 'oportuna.csrf')?.value ?? '';
  const invitationResponse = await adminPage.request.post(`${origin}/api/company/members/invitations`, { headers: { Origin: origin, 'X-CSRF-Token': csrf, 'Content-Type': 'application/json' }, data: { email: invitedEmail, role: 'collaborator' } });
  assert.equal(invitationResponse.status(), 201);
  const invitation = await invitationResponse.json() as any;
  assert.equal(invitation.delivery, 'simulated');
  const inbox = await adminPage.request.get(`${origin}/api/auth/local-outbox?email=${encodeURIComponent(invitedEmail)}&purpose=invitation`);
  const invitationMail = (await inbox.json() as any).messages[0];
  assert.ok(invitationMail.link.includes(invitation.invitationToken));
  const wrongEmail = await adminPage.request.post(`${origin}/api/auth/register`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { firstName: 'Otro', lastName: 'Correo', email: `wrong-${suffix}@invalid.example`, password, invitationToken: invitation.invitationToken } });
  assert.equal(wrongEmail.status(), 400, 'an invitation cannot be registered with another email');

  const invitePage = await browser.newPage({ viewport: { width: 768, height: 1024 } });
  await invitePage.goto(invitationMail.link);
  await invitePage.getByLabel('Nombre').fill('Colaborador');
  await invitePage.getByLabel('Apellido').fill('Invitado');
  await invitePage.getByLabel('Correo electrónico').fill(invitedEmail);
  await invitePage.getByLabel('Contraseña').fill(password);
  await invitePage.getByRole('button', { name: 'Crear cuenta y verificar correo' }).click();
  await invitePage.getByRole('heading', { name: 'Revisa tu correo' }).waitFor();
  await invitePage.getByRole('button', { name: 'Buzón local de prueba' }).click();
  await invitePage.getByRole('link', { name: 'Abrir enlace de verificación simulado' }).click();
  await invitePage.getByRole('button', { name: 'Verificar cuenta' }).click();
  await invitePage.getByText('Licitaciones', { exact: true }).first().waitFor({ timeout: 8000 });
  await invitePage.screenshot({ path: 'artifacts/qa-email/invitation-tablet.png', fullPage: true });
  const invitedAccount = await pool.query<any[]>('SELECT id FROM app_users WHERE email_normalized=?', [invitedEmail]);
  userIds.push(Number(invitedAccount[0][0].id));
  const [membership] = await pool.query<any[]>('SELECT role,status FROM company_memberships WHERE user_id=? AND company_id=?', [userIds[userIds.length - 1], companyId]);
  assert.equal(membership[0]?.status, 'active');
  assert.equal(membership[0]?.role, 'collaborator');

  const expired = await desktop.request.post(`${origin}/api/auth/register`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { firstName: 'Correo', lastName: 'Vencido', email: expiredEmail, password } });
  assert.equal(expired.status(), 201);
  const [expiredUser] = await pool.query<any[]>('SELECT id FROM app_users WHERE email_normalized=?', [expiredEmail]);
  userIds.push(Number(expiredUser[0].id));
  await pool.execute('UPDATE email_verification_tokens SET expires_at=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 MINUTE) WHERE user_id=? AND used_at IS NULL', [expiredUser[0].id]);
  const expiredInbox = await desktop.request.get(`${origin}/api/auth/local-outbox?email=${encodeURIComponent(expiredEmail)}&purpose=verification`);
  const expiredMail = (await expiredInbox.json() as any).messages[0];
  const expiredPage = await browser.newPage({ viewport: { width: 375, height: 667 } });
  await expiredPage.goto(expiredMail.link);
  await expiredPage.getByRole('button', { name: 'Verificar cuenta' }).click();
  await expiredPage.getByText(/enlace de verificación no es válido/i).waitFor();
  await expiredPage.screenshot({ path: 'artifacts/qa-email/expired-link-mobile.png', fullPage: true });
  const expiredConfirm = await desktop.request.post(`${origin}/api/auth/email-verification/confirm`, { headers: { Origin: origin, 'Content-Type': 'application/json' }, data: { token: new URL(expiredMail.link).searchParams.get('verifyEmail') } });
  assert.equal(expiredConfirm.status(), 400);
  console.log('PASS Playwright: registro sin verificar, bloqueo, verificación un uso, recuperación neutra, invitación ligada al correo y expiración. Viewports 1440×900, 768×1024 y 390×844.');
} catch (error) {
  console.error('FAIL email access Playwright:', error instanceof Error ? error.message : 'error desconocido');
  process.exitCode = 1;
} finally {
  await browser.close();
  try {
    if (companyId) await pool.execute('DELETE FROM companies WHERE id=?', [companyId]);
    if (userIds.length) await pool.execute(`DELETE FROM app_users WHERE id IN (${userIds.map(() => '?').join(',')})`, userIds);
    const [left] = await pool.query<any[]>('SELECT COUNT(*) total FROM companies WHERE nombre_comercial LIKE ?', [`TEMP EMAIL QA ${suffix}%`]);
    assert.equal(Number(left[0].total), 0);
  } catch (error) { console.error('FAIL email QA cleanup:', error instanceof Error ? error.message : 'error desconocido'); process.exitCode = 1; }
  await pool.end();
}
